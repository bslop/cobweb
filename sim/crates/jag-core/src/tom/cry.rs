//! independent of any game-specific palette — so it matches BigPEmu.
//!
//! Byte order per the TRM pixel format (C-R-Y, high to low): cyan `px[15:12]`,
//! red `px[11:8]`, intensity `y = px[7:0]`; `R = CRY_RED[red][cyan] * y / 255`,
